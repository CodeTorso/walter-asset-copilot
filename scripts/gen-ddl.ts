// Regenerates src/server/db/ddl.generated.ts from the Drizzle schema (bun run db:ddl).
import { writeFileSync } from "node:fs"
import { generateDrizzleJson, generateMigration } from "drizzle-kit/api"
import * as schema from "../src/server/db/schema"

const stmts = await generateMigration(generateDrizzleJson({}), generateDrizzleJson(schema))
const body = stmts
  .join("\n")
  .split(/;?\n(?=CREATE )/)
  .map((s) => s.trim().replace(/;$/, ""))
  .filter(Boolean)
writeFileSync(
  new URL("../src/server/db/ddl.generated.ts", import.meta.url),
  `// Generated by scripts/gen-ddl.ts from src/server/db/schema.ts. Do not edit.\nexport const DDL: string[] = ${JSON.stringify(body, null, 2)}\n`,
)
console.log(`wrote ${body.length} statements`)
